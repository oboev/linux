/*
 * BOE AA577 P_3 A0020 DSI command-mode panel — OnePlus 13R (giulia)
 *
 * Copyright (c) 2026
 *
 * Modelled on panel-visionox-vtdr6130.c (same DSI controller, same SoC).
 *
 * The init sequence is transcribed from the OnePlus downstream device tree,
 * LineageOS android_kernel_oneplus_sm8650-devicetrees:
 *   qcom/display/oplus/panel/dsi-panel-AA577-P-3-A0020-dsc-cmd.dtsi
 * property qcom,mdss-dsi-on-command of timing@sdc_fhd_120 (614 commands).
 *
 * Notes:
 *
 *  - The DSC PPS goes out as the vendor's 100-byte DCS 0x81 write
 *    (command #6 of 614), verbatim and in the vendor position — before
 *    exit_sleep_mode and set_display_on. This panel never receives a
 *    standard PPS packet (0x0A) or compression-mode command (0x07); its
 *    entire vendor sequence uses only DCS 0x15 and 0x39. The msm DSI host
 *    does not transmit PPS itself — dsi_populate_dsc_params() only fills
 *    the config — so the panel owns it, as in panel-novatek-nt37801.c.
 *
 *  - aa577_dsc supplies only the fields the host does not derive. The host
 *    sets simple_422, convert_rgb, vbr_enable, the rc_* tables and
 *    line_buf_depth = bits_per_component + 1. That last one computes to 11,
 *    which matches the vendor PPS exactly — a useful cross-check that the
 *    DSC parameters here are right.
 *
 *  - Only the 120 Hz mode is implemented. The downstream tree also defines
 *    sdc_fhd_90, sdc_fhd_60 and oplus_fhd_120, each with its own full init
 *    sequence. Porches and DSI bit clock are identical across all four.
 *
 *  - Downstream ADFR, OFP/AOD, PWM dimming, demura and the "oplus" backlight
 *    remapping are deliberately not implemented. They have no mainline
 *    equivalent and are not needed to light the panel.
 */

